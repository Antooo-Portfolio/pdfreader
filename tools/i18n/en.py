def main():
    cat = json.load(open(CATALOG, encoding="utf-8"))
    missing = []
    for k in cat:
        if k in EN:
            cat[k] = EN[k]
        elif not cat[k]:
            missing.append(k)
    with open(CATALOG, "w", encoding="utf-8", newline="\n") as f:
        json.dump(cat, f, ensure_ascii=False, indent=2)
        f.write("\n")
    unused = [k for k in EN if k not in cat]
    print(f"{len(cat) - len(missing)} / {len(cat)} traduites ; {len(unused)} traduction(s) inutilisée(s)")
    for k in missing:
        print("  manque :", k)
    # Les variables {x} doivent être les mêmes des deux côtés.
    import re
    for k, v in cat.items():
        if v and sorted(re.findall(r"\{\w+\}", k)) != sorted(re.findall(r"\{\w+\}", v)):
            print("  variables différentes :", k, "→", v)


main()
